#!/usr/bin/env node

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = path.join(repositoryRoot, "contracts", "scene-recipe.v1.schema.json");
const playableSchemaPath = path.join(repositoryRoot, "contracts", "playable-scenes.v1.schema.json");
const playableCatalogPath = path.join(
  repositoryRoot,
  "assets",
  "scenes",
  "playable-scenes.v1.json",
);
const sceneIndexPath = path.join(repositoryRoot, "assets", "scenes", "index.json");
const fixturePath = path.join(
  repositoryRoot,
  "contracts",
  "fixtures",
  "scene-recipe.v1.conformance.json",
);
const generatedBindingPath = path.join(
  repositoryRoot,
  "apps",
  "client",
  "lib",
  "domain",
  "generated",
  "scene_recipe_contract.g.dart",
);

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function generatedBinding(schemaBytes, schema) {
  const schemaVersion = schema.properties?.schemaVersion?.const;
  if (!Number.isInteger(schemaVersion)) {
    throw new Error("SceneRecipe schema must declare an integer schemaVersion const.");
  }
  const digest = crypto.createHash("sha256").update(schemaBytes).digest("hex");
  return (
    `// Generated by tools/validate-contracts.mjs. Do not edit.\n` +
    `const int sceneRecipeSchemaVersion = ${schemaVersion};\n` +
    `const String sceneRecipeSchemaSha256 =\n` +
    `    '${digest}';\n`
  );
}

const schemaBytes = fs.readFileSync(schemaPath);
const schema = JSON.parse(schemaBytes.toString("utf8"));
const playableSchema = readJson(playableSchemaPath);
const playableCatalog = readJson(playableCatalogPath);
const sceneIndex = readJson(sceneIndexPath);
const fixtures = readJson(fixturePath);
if (fixtures.schemaVersion !== 1) {
  throw new Error("Unsupported SceneRecipe conformance fixture schema.");
}

const ajv = new Ajv2020({ allErrors: true, strict: true });
ajv.addSchema(schema);
const validateRecipe = ajv.getSchema(schema.$id);
const validatePlayableCatalog = ajv.compile(playableSchema);
for (const fixture of fixtures.valid ?? []) {
  if (!validateRecipe(fixture.value)) {
    throw new Error(
      `Valid fixture '${fixture.name}' failed: ${ajv.errorsText(validateRecipe.errors)}`,
    );
  }
}
for (const fixture of fixtures.invalid ?? []) {
  if (validateRecipe(fixture.value)) {
    throw new Error(`Invalid fixture '${fixture.name}' unexpectedly passed.`);
  }
}

if (!validatePlayableCatalog(playableCatalog)) {
  throw new Error(
    `Playable scene catalog failed: ${ajv.errorsText(validatePlayableCatalog.errors)}`,
  );
}

const registeredSceneIds = new Set(sceneIndex.scenes.map((scene) => scene.id));
const playableSceneIds = new Set();
for (const playable of playableCatalog.scenes) {
  if (playableSceneIds.has(playable.sceneId)) {
    throw new Error(`Duplicate playable scene id: ${playable.sceneId}.`);
  }
  playableSceneIds.add(playable.sceneId);
  if (!registeredSceneIds.has(playable.sceneId)) {
    throw new Error(`Playable scene is not registered: ${playable.sceneId}.`);
  }
  if (playable.recipe.sceneId !== playable.sceneId) {
    throw new Error(`Recipe sceneId does not match playable scene ${playable.sceneId}.`);
  }
  const layerIds = playable.recipe.layers.map((layer) => layer.id);
  if (new Set(layerIds).size !== layerIds.length) {
    throw new Error(`Playable scene ${playable.sceneId} contains duplicate layer ids.`);
  }
  for (const layer of playable.recipe.layers) {
    if (layer.eventPolicy.maximumSilenceMs < layer.eventPolicy.minimumSilenceMs) {
      throw new Error(`${playable.sceneId}/${layer.id} has an inverted silence range.`);
    }
    if (
      layer.dynamics.maximumChangeIntervalMs < layer.dynamics.minimumChangeIntervalMs ||
      layer.dynamics.maximumTransitionMs < layer.dynamics.minimumTransitionMs
    ) {
      throw new Error(`${playable.sceneId}/${layer.id} has an inverted dynamics range.`);
    }
  }
}
if (!playableSceneIds.has(sceneIndex.defaultScene)) {
  throw new Error(`Default scene ${sceneIndex.defaultScene} must be playable.`);
}

const expectedBinding = generatedBinding(schemaBytes, schema);
if (process.argv.includes("--write")) {
  fs.mkdirSync(path.dirname(generatedBindingPath), { recursive: true });
  fs.writeFileSync(generatedBindingPath, expectedBinding, "utf8");
} else if (
  !fs.existsSync(generatedBindingPath) ||
  fs.readFileSync(generatedBindingPath, "utf8") !== expectedBinding
) {
  throw new Error("Generated SceneRecipe binding is stale. Run npm run contracts:sync.");
}

console.log(
  `[soundscape] SceneRecipe contract verified ` +
    `(${fixtures.valid.length} valid, ${fixtures.invalid.length} invalid fixtures, ` +
    `${playableCatalog.scenes.length} playable scenes).`,
);
